let LANG = 'ru';
function resolveLang(pref) {
  if (pref === 'ru' || pref === 'en') return pref;
  const l = (navigator.language || '').toLowerCase();
  return /^(ru|uk|be|kk)/.test(l) ? 'ru' : 'en';
}
function L(ru) { return LANG === 'en' && EN[ru] ? EN[ru] : ru; }
function tf(key, ...a) { return FMT[key][LANG](...a); }

// перевод разметки: запоминаем русский оригинал у каждого текста и атрибута
const ATTRS = ['placeholder', 'title', 'aria-label'];
function translateStatic(rootEl) {
  const walker = document.createTreeWalker(rootEl, NodeFilter.SHOW_TEXT);
  for (let n; (n = walker.nextNode());) {
    if (n.parentElement && n.parentElement.closest('#root, script, style')) continue;
    if (n.__ru === undefined) n.__ru = n.nodeValue;
    const key = n.__ru.trim();
    if (!key) continue;
    n.nodeValue = LANG === 'en' && EN[key] ? n.__ru.replace(key, EN[key]) : n.__ru;
  }
  rootEl.querySelectorAll('[placeholder], [title], [aria-label]').forEach(e => {
    if (e.closest('#root')) return;
    for (const a of ATTRS) {
      if (!e.hasAttribute(a)) continue;
      const store = 'ru' + a.replace(/-./g, m => m[1].toUpperCase()).replace(/^./, c => c.toUpperCase());
      if (e.dataset[store] === undefined) e.dataset[store] = e.getAttribute(a);
      e.setAttribute(a, L(e.dataset[store]));
    }
  });
}
function applyLang(pref) {
  LANG = resolveLang(pref);
  document.documentElement.lang = LANG;
  document.title = L('Экспресс-панель');
  translateStatic(document.body);
  const r = document.documentElement.style;
  for (const [k, v] of Object.entries(CSS_TEXT)) r.setProperty(k, JSON.stringify(v[LANG]));
}
